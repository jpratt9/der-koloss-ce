import assert from 'node:assert/strict';
import { archiveHarness, moduleTest } from './lib/assets-page-harness.mjs';

await moduleTest(async () => {
  const h = archiveHarness();
  const { createWeaponViewer } = await h.evaluate('js/assets-page/viewer.js');
  assert.equal(h.frames.length, 0, 'import must not start rendering');
  const wrap = h.element('weapon-canvas-wrap');
  const viewer = createWeaponViewer({ canvas: h.element('weapon-canvas'), canvasWrap: wrap });
  assert.equal(h.frames.length, 1);
  assert.deepEqual(h.log.filter(x => x[0] === 'size'), [['size', 640, 400]]);
  viewer.setModel('m1911', false, 'standard'); h.frame();
  assert.equal(h.frames.length, 1, 'each frame schedules exactly one successor');
  const { scene, camera } = h.renders.at(-1);
  const pivot = scene.children.find(x => x.isGroup), mount = pivot.children[0];
  assert.equal(camera.aspect, 1.6);
  assert.equal(mount.scale.x, 0.64, 'fit uses the visible 2-unit mesh, excluding giant hidden geometry and sprite');
  assert.equal(mount.position.y, camera.position.y);
  const centerMount = mount.children[0].children[0];
  assert.equal(Math.abs(centerMount.position.y), 0, 'model must settle out of holster pose before bounds are measured');
  assert.equal(viewer.weaponRig.current.group.children[1].visible, false, 'glove is hidden');
  assert.equal(viewer.weaponRig.current.group.children[0].visible, true, 'weapon mesh remains visible');
  await wrap.emit('pointerdown', { clientX: 0, clientY: 0, pointerId: 1 });
  await wrap.emit('pointermove', { clientX: 100, clientY: 1000 }); h.frame();
  assert.equal(pivot.rotation.x, 0.65); assert.ok(Math.abs(pivot.rotation.y - 0.52) < 1e-9);
  await wrap.emit('pointermove', { clientX: 100, clientY: -1000 }); h.frame();
  assert.equal(pivot.rotation.x, -0.65);
  await wrap.emit('pointerup', { pointerId: 1 });
  viewer.resetView(); h.reduceMotion(true); h.frame();
  assert.equal(pivot.rotation.x, -0.12); assert.equal(pivot.rotation.y, -0.28);
  h.frame(5000); assert.equal(pivot.rotation.y, -0.28, 'reduced motion disables idle rotation');
  assert.equal(h.log.filter(x => x[0] === 'update').at(-1)[1], 0.05, 'long frames are clamped');
  h.reduceMotion(false); h.frame(100); assert.ok(pivot.rotation.y > -0.28);
  const yaw = pivot.rotation.y;
  viewer.setModel('m1911', false, 'gold'); h.reduceMotion(true); h.frame();
  assert.equal(pivot.rotation.y, yaw, 'same-weapon finish change keeps orientation');
  assert.ok(h.log.some(x => x[0] === 'gold'));
  viewer.setModel('m1911', true, 'diamond'); assert.equal(viewer.weaponRig.diamondNext, true);
  assert.ok(h.log.some(x => x[0] === 'diamond'));
  viewer.setModel('mp40', true, 'pap'); h.frame();
  assert.equal(pivot.rotation.y, -0.28, 'new weapon resets orientation');
  assert.equal(pivot.children.length, 1, 'replacement removes the old mount');
  assert.equal(h.frames.length, 1);
  console.log('Asset viewer OK: isolated startup, bounds and rest pose, finishes, drag/reset, resize and one clamped frame loop.');
});
